#!/usr/bin/env python3
"""Generate Apple/Shared/Viz/VizScenes.metal from the web GLSL scene programs (viz_shaders.js).
   usage: gen_metal_viz.py <path to viz_shaders.js> <out .metal>
   Each scene becomes `struct S_<name>` (so uniform access and helper functions share one scope) plus a fragment entry `scene_<name>`.
   Uniform buffer K (56 floats): [0,1] res  [2] time  [3] quality  [4] dt  [5,6] state res  [7] point size  [8..16] bands  [24..55] u[0..31]."""
import re, subprocess, sys, json
src, out = sys.argv[1], sys.argv[2]
js = subprocess.check_output(['node', '-e', "const fs=require('fs');const f=new Function(fs.readFileSync(process.argv[1],'utf8')+';return {H:VIZ_GLSL_HEAD,S:VIZ_GLSL,SIM:VIZ_SAND_SIM}')();console.log(JSON.stringify(f))", src])
D = json.loads(js)

def split_top(code):
    items, depth, cur, i = [], 0, '', 0
    while i < len(code):
        c = code[i]; cur += c
        if c == '{': depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0: items.append(('fn', cur.strip())); cur = ''
        elif c == ';' and depth == 0: items.append(('decl', cur.strip())); cur = ''
        i += 1
    if cur.strip(): items.append(('fn', cur.strip()))
    return items

def call_args(s, start):
    """s[start] == '(' -> (list of top-level args, index after ')')"""
    d, a, cur, i = 0, [], '', start
    while i < len(s):
        c = s[i]
        if c == '(': d += 1; 
        if c == ')':
            d -= 1
            if d == 0: a.append(cur[1:] if cur.startswith('(') else cur); return a, i + 1
        if c == ',' and d == 1: a.append(cur[1:] if not a else cur); cur = ''; i += 1; continue
        cur += c; i += 1
    raise ValueError('unbalanced')

def rewrite_calls(s, name, fn):
    res, i = '', 0
    pat = re.compile(r'\b' + name + r'\(')
    while True:
        m = pat.search(s, i)
        if not m: res += s[i:]; break
        res += s[i:m.start()]; args, end = call_args(s, m.end() - 1); args = [rewrite_calls(a, name, fn) for a in args]; res += fn(args); i = end
    return res

def conv(s):
    s = re.sub(r'#version.*\n', '', s); s = re.sub(r'precision\s+\w+\s+float\s*;', '', s)
    s = re.sub(r'^\s*(uniform|in|out|flat in|flat out)\b[^;{}]*;', '', s, flags=re.M)
    s = re.sub(r'\buniform\s+[^;{}]*;', '', s); s = re.sub(r'\bout\s+vec4\s+oC\s*;', '', s)
    s = re.sub(r'\bvec([234])\b', r'float\1', s); s = re.sub(r'\bivec([234])\b', r'int\1', s); s = re.sub(r'\bmat2\b', 'float2x2', s); s = re.sub(r'\bmat3\b', 'float3x3', s)
    s = re.sub(r'\bmod\(', 'glmod(', s); s = re.sub(r'(?<![\w.])(min|max|clamp|mix|step|smoothstep)\(', r'g\1(', s); s = s.replace('inversesqrt(', 'rsqrt(')
    s = rewrite_calls(s, 'atan', lambda a: ('atan2(%s,%s)' % (a[0], a[1])) if len(a) == 2 else 'atan(%s)' % a[0])
    s = rewrite_calls(s, 'texture', lambda a: '%s.sample(smp,float2((%s).x,1.-(%s).y))' % (a[0], a[1], a[1]))
    s = s.replace('gl_FragCoord.xy', 'fcoord').replace('gl_FragCoord.yx', 'fcoord.yx').replace('discard;', 'discard_fragment();')
    return s

PRE = '''// GENERATED by tools/gen_metal_viz.py from the web GLSL scene programs - do not edit by hand.
#include <metal_stdlib>
using namespace metal;
constant float PI = 3.14159265358979323846;
constant float TAU = 6.28318530717958647692;
struct QuadOut { float4 pos [[position]]; float2 uv; };
constexpr sampler smp(filter::linear, address::clamp_to_edge);
constexpr sampler smpN(filter::nearest, address::clamp_to_edge);
template <class T, class U> inline T glmod(T x, U y) { return x - y * floor(x / y); }
template <class A, class B> inline A gmin(A a, B b) { return min(a, A(b)); }
template <class A, class B> inline A gmax(A a, B b) { return max(a, A(b)); }
template <class A, class B> inline A gclamp(A x, B lo, B hi) { return clamp(x, A(lo), A(hi)); }
template <class A, class B> inline A gmix(A x, A y, B t) { return mix(x, y, A(t)); }
template <class E, class X> inline X gstep(E e, X x) { return step(X(e), x); }
template <class E, class X> inline X gsmoothstep(E a, E b, X x) { return smoothstep(X(a), X(b), x); }
#define uRes float2(K[0], K[1])
#define uTime K[2]
#define uQ K[3]
#define uDt K[4]
#define uStateRes float2(K[5], K[6])
#define uA (K + 8)
#define uU (K + 24)
#define U(i) uU[i]
'''
parts = [PRE]
head_items = split_top(conv(D['H']))
glob = [t for k, t in head_items if k == 'decl' and t.startswith('const')]
for g in glob: parts.append('constant ' + g[len('const '):] + '\n')
head_fns = [t for k, t in head_items if k == 'fn']
def emit(name, body_src, extra_members='', entry_params='', entry_init=''):
    items = split_top(conv(body_src)); fns = []
    for k, t in items:
        if k == 'decl' and t.startswith('const'): parts.append('constant ' + t[len('const '):] + '\n')
        elif k == 'fn': fns.append(t)
        elif k == 'decl' and t: fns.append(t)
    mine = [f for f in head_fns if not re.match(r'^\w+\s+main\s*\(', f)] + [re.sub(r'\bvoid\s+main\s*\(\s*\)', 'void main_()', f) for f in fns]
    parts.append('struct S_%s { constant float* K; float2 fcoord; float4 oC; %s\n  %s\n};\n' % (name, extra_members, '\n  '.join(mine)))
    parts.append('fragment float4 scene_%s(QuadOut in [[stage_in]], constant float* K [[buffer(0)]]%s) { S_%s s; s.K = K; s.fcoord = float2(in.pos.x, K[1] - in.pos.y); s.oC = float4(0.); %s s.main_(); return s.oC; }\n' % (name, entry_params, name, entry_init))
for n, g in D['S'].items():
    if n == 'sand_plate': continue
    emit(n, g)
# the sand plate scene program renders the plate itself (shading); the particles are drawn separately
emit('sand_plate', D['S']['sand_plate'])
# sand state update: a fragment pass writing the next state texture
sim = D['SIM']; sim = re.sub(r'\buStateRes\b', 'uStateRes', sim)
sim_items = split_top(conv(sim).replace('.sample(smp,', '.sample(smpN,')); sim_fns = []
for k, t in sim_items:
    if k == 'decl' and t.startswith('const'): parts.append('constant ' + t[len('const '):] + '\n')
    elif k == 'fn': sim_fns.append(re.sub(r'\bvoid\s+main\s*\(\s*\)', 'void main_()', t))
parts.append('struct S_sandsim { constant float* K; float2 fcoord; float4 oC; texture2d<float> uState;\n  %s\n};\n' % '\n  '.join(sim_fns))
parts.append('fragment float4 sand_sim(QuadOut in [[stage_in]], constant float* K [[buffer(0)]], texture2d<float> st [[texture(0)]]) { S_sandsim s; s.K = K; s.fcoord = float2(in.pos.x, uStateRes.y - in.pos.y); s.uState = st; s.oC = float4(0.); s.main_(); return s.oC; }\n')
txt = ''.join(parts)
known = set('float float2 float3 float4 float2x2 float3x3 int int2 int3 int4 if for while return abs floor fract sin cos tan atan atan2 sqrt exp log exp2 log2 pow sign dot length normalize cross reflect tanh sinh cosh rsqrt round ceil trunc fmod discard_fragment sample main_ glmod gmin gmax gclamp gmix gstep gsmoothstep U K uRes uStateRes asin acos fabs distance fract mod'.split())
defined = set(re.findall(r'\b(\w+)\s*\([^()]*\)\s*\{', txt)) | set(re.findall(r'\b(?:float\d?|int|void)\s+(\w+)\s*\(', txt))
unk = sorted(set(m for m in re.findall(r'\b([A-Za-z_]\w*)\s*\(', txt) if m not in known and m not in defined and not m.startswith(('S_','scene_','sand_'))))
if unk: print('LINT: unknown call identifiers:', unk)
if re.search(r'\b(vec[234]|mat[234]|gl_\w+|texelFetch)\b', txt): print('LINT: leftover GLSL tokens:', set(re.findall(r'\b(vec[234]|mat[234]|gl_\w+|texelFetch)\b', txt)))
open(out, 'w').write(txt); print('wrote', out, len(''.join(parts)), 'bytes;', len(D['S']), 'scenes + sand sim')
