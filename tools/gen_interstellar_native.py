#!/usr/bin/env python3
"""Generates the native Interstellar UI pieces from Assets/Interstellar/presets.json:
   Juce/Source/InterstellarPresets.h, Juce/Source/InterstellarUi.inc,
   Apple/Shared/InterstellarPresets.swift, Apple/Shared/InterstellarUi.swift.inc (pasted into FXRackView by hand-free include below)."""
import json, os
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(R + '/Assets/Interstellar/presets.json'))
D = d['defaults']; P = d['presets']

def sec(t): return ('sec', t)
def K(label, key, lo, hi, fmt='%.2f', unit='', log=False): return ('k', label, key, lo, hi, fmt, unit, log)
def C(label, key, opts): return ('c', label, key, opts)
def T(label, key): return ('t', label, key)
SPEC = [
 sec('Source'), C('Source', 'source', ['live', 'capture']), T('Freeze', 'freeze'), ('cap',), K('Capture length', 'captureLen', 0.25, 16, '%.2f', ' s'), K('Live span', 'span', 1, 16, '%.1f', ' s'),
 sec('Analysis bands (dB)'), K('Tonal focus', 'tonal', 0, 1), K('Sub', 'band1', -48, 12, '%.1f', ' dB'), K('Low', 'band2', -48, 12, '%.1f', ' dB'), K('Low-mid', 'band3', -48, 12, '%.1f', ' dB'),
 K('High-mid', 'band4', -48, 12, '%.1f', ' dB'), K('High', 'band5', -48, 12, '%.1f', ' dB'), K('Air', 'band6', -48, 12, '%.1f', ' dB'),
 sec('Chop / loop / stretch'), K('Segments', 'segments', 1, 16, '%.0f'), T('Tempo sync', 'segSync'), C('Division', 'segDiv', ['1/32', '1/16', '1/8', '1/4', '1/2', '1/1', '2/1', '4/1']),
 K('Time', 'segTime', 0.25, 16, '%.2f', ' s'), C('Order', 'segOrder', ['forward', 'reverse', 'random', 'walk', 'pingpong']), K('Stretch', 'stretch', 1, 50, '%.1f', 'x', True), K('Bloom', 'bloom', 0, 1),
 sec('Particles'), K('Density', 'density', 0, 1), K('Life', 'life', 0.5, 20, '%.1f', ' s', True), K('Pitch up', 'pitchUp', 0, 24, '%.0f', ' st'), K('Up chance', 'upProb', 0, 1),
 K('Pitch down', 'pitchDown', 0, 24, '%.0f', ' st'), K('Down chance', 'downProb', 0, 1), K('Body', 'body', 0, 1), K('Particles', 'particles', 0, 1), K('Spread', 'spread', 0, 1),
 sec('Key / scale'), C('Snap', 'snap', ['key', 'fifths', 'free']), C('Scale', 'scale', ['auto', 'major', 'minor', 'dorian', 'lydian', 'pentMajor', 'pentMinor', 'whole']), K('Key (-1 auto)', 'key', -1, 11, '%.0f'),
 sec('Harmonic resonators'), K('Resonance', 'resonance', 0, 1), K('Ring', 'ring', 0.2, 12, '%.1f', ' s', True), K('Strum', 'strum', 0, 1), C('Tuned from', 'resTune', ['segment', 'key', 'fifths']),
 sec('Motion'), K('Evolve', 'evolve', 0, 1), K('Drift', 'drift', 0, 1),
 sec('Space'), K('Space', 'space', 0, 1), K('Size', 'size', 0, 1), K('Decay', 'decay', 0, 1), K('Predelay', 'predelay', 0, 0.35, '%.3f', ' s'), K('Damping', 'damp', 0, 1), K('Modulation', 'revMod', 0, 1),
 K('Width', 'width', 0, 1), K('Shimmer', 'shimmer', 0, 1), T('Reverb freeze', 'revFreeze'),
 sec('Master'), K('Character', 'character', 0, 1), C('Quality', 'quality', ['eco', 'normal', 'lush']), K('Mix (dry / wet)', 'mix', 0, 1), K('Level', 'level', -36, 12, '%.1f', ' dB'),
]
# every continuous dial is a modulation destination (the same list is in Core mod_defs.hpp and the web FXP_DEFS)
MOD_KEYS = [s[2] for s in SPEC if s[0] == 'k' and s[2] not in ('key', 'captureLen')] + ['freeze', 'revFreeze']
def num(x): return repr(float(x)) if not float(x).is_integer() else str(int(x))
def dv(k): return D[k]

# ---------------- JUCE
j = []
for s in SPEC:
    if s[0] == 'sec': j.append('p.newRow(); { auto* l = new juce::Label({}, "%s"); l->setColour(juce::Label::textColourId, col::dim); p.customOwned(l, -1, 22); } p.newRow();' % s[1].upper())
    elif s[0] == 'k':
        o = '{ "%s", "%s", %s, %d }' % (s[5], s[6], 'true' if s[7] else 'false', 0 if s[5] in ('%.0f',) else int(s[5][2]))
        j.append('K("%s", "%s", %s, %s, %s, %s);' % (s[1], s[2], num(s[3]), num(s[4]), num(dv(s[2])), o))
    elif s[0] == 'c': j.append('p.choice("%s", q + "%s", { %s }, "%s");' % (s[1], s[2], ', '.join('"%s"' % x for x in s[3]), dv(s[2])))
    elif s[0] == 't': j.append('p.toggle("%s", q + "%s");' % (s[1], s[2]))
    elif s[0] == 'cap': j.append('{ auto* b = new juce::TextButton("CAPTURE NOW"); b->onClick = [&store = s, q] { store.set(q + "capture", (int) store.get(q + "capture") + 1); }; p.customOwned(b, 130, 34); }')
open(R + '/Juce/Source/InterstellarUi.inc', 'w').write('// GENERATED by tools/gen_interstellar_native.py - do not edit.\n' + '\n'.join(j) + '\n')
h = ['// GENERATED by tools/gen_interstellar_native.py from Assets/Interstellar/presets.json - do not edit.', '#pragma once', 'namespace vv::isp {', 'struct Preset { const char* category; const char* name; const char* json; };', 'inline const Preset kPresets[] = {']
for p in P: h.append('    { "%s", "%s", R"VVJ(%s)VVJ" },' % (p['category'], p['name'], json.dumps(p['params'], separators=(',', ':'))))
h += ['};', 'inline const char* kDefaultsJson = R"VVJ(%s)VVJ";' % json.dumps(D, separators=(',', ':')), '}']
open(R + '/Juce/Source/InterstellarPresets.h', 'w').write('\n'.join(h) + '\n')

# ---------------- Swift
def sw(s):
    if s[0] == 'sec': return 'Text("%s").font(.caption2.bold()).foregroundStyle(.secondary).padding(.top, 6)' % s[1].upper()
    if s[0] == 'k':
        fmt = s[5]; extra = (', fmt: "%s"' % fmt if fmt != '%.2f' else '') + (', log: true' if s[7] else '') + (', unit: "%s"' % s[6] if s[6] else '')
        return 'sl("%s", "%s", %s...%s, %s%s)' % (s[1], s[2], num(s[3]), num(s[4]), num(dv(s[2])), extra)
    if s[0] == 'c': return 'pk("%s", "%s", [%s])' % (s[1], s[2], ', '.join('"%s"' % x for x in s[3]))
    if s[0] == 't': return 'tg("%s", "%s")' % (s[1], s[2])
    if s[0] == 'cap': return 'Button("Capture now") { s.set("\\(base).params.capture", s.int("\\(base).params.capture") + 1) }.buttonStyle(.bordered)'
sl_ = ['struct InterstellarParams: View {', '    @ObservedObject var s: PresetStore', '    let base: String',
  '    private func sl(_ label: String, _ key: String, _ r: ClosedRange<Double>, _ def: Double = 0, fmt: String = "%.2f", log: Bool = false, unit: String = "") -> some View {',
  '        SliderRow(s: s, label: label, path: "\\(base).params.\\(key)", range: r, def: def, fmt: fmt, log: log, unit: unit)', '    }',
  '    private func pk(_ label: String, _ key: String, _ opts: [String]) -> some View { PickerRow(s: s, label: label, path: "\\(base).params.\\(key)", options: opts) }',
  '    private func tg(_ label: String, _ key: String) -> some View { ToggleRow(s: s, label: label, path: "\\(base).params.\\(key)", def: false) }',
  '    var body: some View {', '        InterstellarPresetMenu(s: s, base: base)']
groups = []
for x in SPEC:
    if x[0] == 'sec': groups.append([x])
    else: groups[-1].append(x)
sl_ += ['        Group {', '            InterstellarPresetMenu(s: s, base: base)']
for gi, g in enumerate(groups):
    if gi == 5: sl_ += ['        }', '        Group {']
    sl_ += ['            Group {'] + ['                ' + sw(x) for x in g] + ['            }']
sl_ += ['        }', '    }', '}']
sl_ += open(R + '/tools/interstellar_preset_menu.swift.tpl').read().split('\n')
open(R + '/Apple/Shared/InterstellarUi.swift', 'w').write('// GENERATED by tools/gen_interstellar_native.py - do not edit.\n// NOTE: written without a Mac. Not compiled yet.\nimport SwiftUI\n\n' + '\n'.join(sl_) + '\n')
def esc(x): return x.replace('\\', '\\\\').replace('"', '\\"')
w = ['// GENERATED by tools/gen_interstellar_native.py from Assets/Interstellar/presets.json - do not edit.', 'import Foundation', '', 'enum InterstellarPresets {', '    static let all: [(category: String, name: String, json: String)] = [']
for p in P: w.append('        ("%s", "%s", "%s"),' % (p['category'], p['name'], esc(json.dumps(p['params'], separators=(',', ':')))))
w += ['    ]', '    static let defaultsJSON = "%s"' % esc(json.dumps(D, separators=(',', ':'))),
 '    static let modKeys: [String] = [%s]' % ', '.join('"%s"' % k for k in MOD_KEYS), '}']
open(R + '/Apple/Shared/InterstellarPresets.swift', 'w').write('\n'.join(w) + '\n')
open(R + '/tools/interstellar_modkeys.txt', 'w').write('\n'.join('FXP:interstellar:' + k for k in MOD_KEYS) + '\n')
print('ok', len(MOD_KEYS), 'mod keys')
