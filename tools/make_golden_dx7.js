// Extracts the DX7 ROM banks as .syx files and renders reference audio from the web app's own Dx7Core (the null-test reference).
// usage: node tools/make_golden_dx7.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'Web/full-app.html'), 'utf8');
const core = html.match(/<script id="dx7-core-main">([\s\S]*?)<\/script>/)[1];
const romSrc = core.match(/const DX7_ROM_B64 = \{([\s\S]*?)\n\s*\};/)[1];
const roms = {}; for (const m of romSrc.matchAll(/'(ROM\d[AB])':\s*"([^"]+)"/g)) roms[m[1]] = Buffer.from(m[2], 'base64');
const Dx7Core = new Function(core.slice(0, core.indexOf("if (typeof module")) + '\nreturn Dx7Core;')();
for (const k of Object.keys(roms)) fs.writeFileSync(path.join(root, 'Assets/DX7', k + '.syx'), roms[k]);
const sr = 48000, out = path.join(root, 'Core/tests/golden_dx7'); fs.mkdirSync(out, { recursive: true });
const scen = [ ['ROM1A',0,60,100,0], ['ROM1A',9,36,40,37], ['ROM1B',3,72,100,0], ['ROM2B',10,84,127,-50], ['ROM3A',20,48,70,0], ['ROM4B',31,60,100,0], ['ROM2A',5,64,90,0], ['INIT',0,60,100,0] ];
const idx = [];
scen.forEach((s, n) => {
  let p; if (s[0] === 'INIT') p = Dx7Core.initPatch(); else p = Dx7Core.parseSysex(roms[s[0]]).voices[s[1]];
  const v = new Dx7Core.Voice(sr); v.noteOn(p, s[2], s[3], 12345);
  const blocks = 600, off = 400, buf = new Float32Array(blocks * 64);
  for (let b = 0; b < blocks; b++) { if (b === off) v.noteOff(); const o = new Float32Array(64); v.renderBlock(o, 0, 440 * Math.pow(2, (s[2] - 69) / 12), s[4]); buf.set(o, b * 64); }
  fs.writeFileSync(path.join(out, 'case' + n + '.bin'), Buffer.from(buf.buffer));
  fs.writeFileSync(path.join(out, 'case' + n + '.patch'), Buffer.from(p));
  idx.push(`${n} ${s[2]} ${s[3]} ${s[4]} ${blocks} ${off}`);
});
fs.writeFileSync(path.join(out, 'index.txt'), idx.join('\n') + '\n');
console.log('wrote', scen.length, 'cases and', Object.keys(roms).length, 'ROM banks');
// Embedded ROM banks for the native engine (no file I/O needed on the audio side or on iOS bundles).
{
  const keys = Object.keys(roms); let h = '// GENERATED by tools/make_golden_dx7.js from the web app DX7 ROM banks (8 x 32 voices, 4104-byte SysEx bulk dumps).\n#pragma once\n#include <cstdint>\n#include <cstring>\nnamespace vv { namespace dx7roms {\n';
  for (const k of keys) h += `static const uint8_t ${k}[${roms[k].length}] = {${Array.from(roms[k]).join(',')}};\n`;
  h += 'struct Bank { const char* key; const uint8_t* data; unsigned size; };\nstatic const Bank banks[] = {' + keys.map(k => `{"${k}",${k},${roms[k].length}}`).join(',') + '};\nstatic const int kNumBanks = ' + keys.length + ';\n';
  h += 'inline const Bank* find(const char* key) { for (int i = 0; i < kNumBanks; ++i) if (!std::strcmp(banks[i].key, key)) return &banks[i]; return nullptr; }\n}}\n';
  fs.writeFileSync(path.join(root, 'Core/include/vv/dx7_roms.hpp'), h);
}
